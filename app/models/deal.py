from pydantic import BaseModel, ConfigDict, Field
from typing import Optional

class Deal(BaseModel):
    """
    Merchant-authorized transaction terms.

    Unlike PurchaseProposal, these values are generated by AMPP's
    deterministic policy engine.
    """

    model_config = ConfigDict(extra="forbid")
    transaction_id: str
    merchant_id: str
    sku: str
    quantity: int = Field(gt=0)
    base_unit_price: int = Field(gt=0)
    approved_unit_price: int = Field(gt=0)
    total_amount: int = Field(gt=0)

    currency: str = Field(
        min_length=3,
        max_length=3,
    )

    hold_token: str
    expires_at: int = Field(gt=0)

    state: str = Field(
        description="Current transaction state.",
    )

    # AI negotiation metadata
    ai_suggested_unit_price: Optional[int] = None
    ai_decision: Optional[str] = None
    ai_reason: Optional[str] = None
    requested_unit_price: int = Field(gt=0)